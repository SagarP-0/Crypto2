//shit rows and inv shift rows
static void shift_rows(uint8_t state[16]) {
    uint8_t in[16];
    memcpy(in, state, 16);
    for (int c = 0; c < 4; c++) {
        for (int r = 0; r < 4; r++) {
            state[r + 4 * c] = in[r + 4 * ((c + r) % 4)];
        }
    }
}

static void inv_shift_rows(uint8_t state[16]) {
    uint8_t in[16];
    memcpy(in, state, 16);
    for (int c = 0; c < 4; c++) {
        for (int r = 0; r < 4; r++) {
            state[r + 4 * ((c + r) % 4)] = in[r + 4 * c];
        }
    }
}

//same keygen 
static void generate_round_keys(const uint8_t master_key[16], uint8_t keys[NUM_KEYS][16]) {
    memcpy(keys[0], master_key, 16);
    for (int i = 1; i <= NR; i++) {
        memcpy(keys[i], keys[i - 1], 16);
        shift_rows(keys[i]);
        keys[i][0] ^= RCON[i - 1];
    }
}

//standard AEs rounds
static void sub_bytes(uint8_t state[16]) {
    for (int i = 0; i < 16; i++) state[i] = SBOX[state[i]];
}

static void inv_sub_bytes(uint8_t state[16]) {
    for (int i = 0; i < 16; i++) state[i] = INV_SBOX[state[i]];
}

static void add_round_key(uint8_t state[16], const uint8_t key[16]) {
    for (int i = 0; i < 16; i++) state[i] ^= key[i];
}

// GF 2pow8 multiplication modulo the AES reduction polynomial
static uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        uint8_t hi_bit_set = a & 0x80;
        a <<= 1;
        if (hi_bit_set) a ^= 0x1B; /* reduce mod x^8+x^4+x^3+x+1 */
        b >>= 1;
    }
    return p;
}

static void mix_columns(uint8_t state[16]) {
    for (int c = 0; c < 4; c++) {
        uint8_t s0 = state[4 * c + 0];
        uint8_t s1 = state[4 * c + 1];
        uint8_t s2 = state[4 * c + 2];
        uint8_t s3 = state[4 * c + 3];
        state[4 * c + 0] = (uint8_t)(gmul(s0, 2) ^ gmul(s1, 3) ^ s2 ^ s3);
        state[4 * c + 1] = (uint8_t)(s0 ^ gmul(s1, 2) ^ gmul(s2, 3) ^ s3);
        state[4 * c + 2] = (uint8_t)(s0 ^ s1 ^ gmul(s2, 2) ^ gmul(s3, 3));
        state[4 * c + 3] = (uint8_t)(gmul(s0, 3) ^ s1 ^ s2 ^ gmul(s3, 2));
    }
}

static void inv_mix_columns(uint8_t state[16]) {
    for (int c = 0; c < 4; c++) {
        uint8_t s0 = state[4 * c + 0];
        uint8_t s1 = state[4 * c + 1];
        uint8_t s2 = state[4 * c + 2];
        uint8_t s3 = state[4 * c + 3];
        state[4 * c + 0] = (uint8_t)(gmul(s0,14) ^ gmul(s1,11) ^ gmul(s2,13) ^ gmul(s3, 9));
        state[4 * c + 1] = (uint8_t)(gmul(s0, 9) ^ gmul(s1,14) ^ gmul(s2,11) ^ gmul(s3,13));
        state[4 * c + 2] = (uint8_t)(gmul(s0,13) ^ gmul(s1, 9) ^ gmul(s2,14) ^ gmul(s3,11));
        state[4 * c + 3] = (uint8_t)(gmul(s0,11) ^ gmul(s1,13) ^ gmul(s2, 9) ^ gmul(s3,14));
    }
}


/* ENCYPRTION DECYPRTION FUNCTIONS
 * keys[0]      = k_{-1}
 * keys[1..9]   = k_0..k_8  (9 main rounds)
 * keys[10]     = k_9        (final round, no MixColumns)
 */
static void encrypt_block(const uint8_t plaintext[16], const uint8_t keys[NUM_KEYS][16],
                           uint8_t ciphertext[16]) {
    uint8_t state[16];
    memcpy(state, plaintext, 16);

    add_round_key(state, keys[0]);              /* whitening: k_{-1} */

    for (int round = 1; round <= NR - 1; round++) { /* rounds using k_0..k_8 */
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, keys[round]);
    }

    /* final round: no MixColumns, uses k_9 */
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, keys[NR]);

    memcpy(ciphertext, state, 16);
}

/*
 * Direct (non-equivalent) inverse cipher, standard AES-128 decryption
 * structure:
 *   state = ciphertext XOR k_9                (keys[10])
 *   for round = 9 downto 1:
 *       state = InvShiftRows(state)
 *       state = InvSubBytes(state)
 *       state = AddRoundKey(state, keys[round])   (k_8 .. k_0)
 *       state = InvMixColumns(state)
 *   state = InvShiftRows(state)
 *   state = InvSubBytes(state)
 *   state = AddRoundKey(state, keys[0])       (k_{-1})
 */
static void decrypt_block(const uint8_t ciphertext[16], const uint8_t keys[NUM_KEYS][16],
                           uint8_t plaintext[16]) {
    uint8_t state[16];
    memcpy(state, ciphertext, 16);

    add_round_key(state, keys[NR]); /* k_9 */

    for (int round = NR - 1; round >= 1; round--) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, keys[round]); /* k_8 .. k_0 */
        inv_mix_columns(state);
    }

    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, keys[0]); /* k_{-1} */

    memcpy(plaintext, state, 16);
}


//hext to bytes helper
static int hex_to_bytes(const char *hex, uint8_t out[16]) {
    if (strlen(hex) != 32) return 0;
    for (int i = 0; i < 16; i++) {
        unsigned int byte;
        if (sscanf(hex + 2 * i, "%2x", &byte) != 1) return 0;
        out[i] = (uint8_t)byte;
    }
    return 1;
}

static void print_hex_line(const char *label, const uint8_t *data, int len) {
    printf("%-11s: ", label);
    for (int i = 0; i < len; i++) printf("%02x", data[i]);
    printf("\n");
}

//main 
int main(int argc, char *argv[]) {
    if (argc != 4 || (strcmp(argv[1], "enc") != 0 && strcmp(argv[1], "dec") != 0)) {
        fprintf(stderr,
            "Usage:\n"
            "  %s enc <32-hex key> <32-hex plaintext>\n"
            "  %s dec <32-hex key> <32-hex ciphertext>\n",
            argv[0], argv[0]);
        return 1;
    }

    int is_encrypt = (strcmp(argv[1], "enc") == 0);

    uint8_t master_key[16], input_block[16], output_block[16];
    if (!hex_to_bytes(argv[2], master_key)) {
        fprintf(stderr, "Error: key must be exactly 32 hex characters (16 bytes)\n");
        return 1;
    }
    if (!hex_to_bytes(argv[3], input_block)) {
        fprintf(stderr, "Error: input must be exactly 32 hex characters (16 bytes)\n");
        return 1;
    }

    uint8_t keys[NUM_KEYS][16];
    generate_round_keys(master_key, keys);

    printf("=== Software implementation: round keys ===\n");
    print_hex_line("k_-1", keys[0], 16);
    for (int i = 1; i <= NR; i++) {
        char label[8];
        snprintf(label, sizeof(label), "k_%d", i - 1);
        print_hex_line(label, keys[i], 16);
    }

    if (is_encrypt) {
        encrypt_block(input_block, keys, output_block);
    } else {
        decrypt_block(input_block, keys, output_block);
    }

    printf("\n=== Software %s ===\n", is_encrypt ? "encryption" : "decryption");
    print_hex_line("key", master_key, 16);
    print_hex_line(is_encrypt ? "plaintext" : "ciphertext", input_block, 16);
    print_hex_line(is_encrypt ? "ciphertext" : "plaintext", output_block, 16);

    return 0;
}